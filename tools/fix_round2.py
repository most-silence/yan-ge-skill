def patch(path: Path, pairs, must_all=True):
    """成对替换。返回 (成功数, 失败列表)"""
    text = path.read_text(encoding="utf-8")
    ok, fail = 0, []
    for old, new in pairs:
        if old in text:
            text = text.replace(old, new)
            ok += 1
        else:
            fail.append(old[:50])
    path.write_text(text, encoding="utf-8")
    return ok, fail


