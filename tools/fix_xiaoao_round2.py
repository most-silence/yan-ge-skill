#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""fix_xiaoao_round2.py — 笑傲牛熊第二轮修复

第二轮判卷在笑傲牛熊找到 8 处「修出来的错」+ 5 处新旧冲突。
每处都回原文核对过。
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
P = ROOT / "books" / "04-技能" / "笑傲牛熊" / "SKILL.md"


def main():
    t = P.read_text(encoding="utf-8")
    n = 0
    fails = []

    def rep(old, new, tag):
        nonlocal t, n
        if old in t:
            t = t.replace(old, new)
            n += 1
            print(f"  ✓ {tag}")
        else:
            fails.append(tag)
            print(f"  ✗ {tag}")

    # ① 指标 5：不是「债券、商品」，是全球股市互证
    rep("| 5 | **市场间联系** | 不同市场（如债券、商品）之间的联动 |",
        "| 5 | **市场间的相互联系** | **全球股市互证**：从《巴伦周刊》国际版看伦敦、法国、奥地利、荷兰、德国等市场的走势图，每周观察一次。原文没有「债券/商品」 |",
        "指标5 全球股市")

    # ② 「最好=市息率」丢限定
    rep("| 7 | **市息率（P/D）** | 作者说「**其中最好的一个指标是市息率（P/D）**」——股价 ÷ 股息 |",
        "| 7 | **市息率（P/D）** | 股价 ÷ 股息 = 股息率的倒数。作者说「**基本面分析指标**不够可信……其中**最好的一个**是市息率（P/D）」——限定是**基本面指标里最好**，不是 8 个指标里最好 |",
        "市息率限定")

    # ③ 计数修正
    rep("> 全书「期权」出现 **188 次**、「期货」**31 次**，第 9 章整章讲期权。",
        "> 全书「期权」出现 **175 次**、「期货」**28 次**；第 9 章讲**期权 + 基金 + 期货**三块。",
        "期权期货计数")
    rep("7. **第 7、9 章讲了卖空与期权**（期权 188 次、期货 31 次）。杠杆只指期权自带，**没有融资融券**。",
        "7. **第 7、9 章讲了卖空、期权、基金、期货**（期权 175 次、期货 28 次）。杠杆只指期权自带，**没有融资融券**。",
        "Critical Reminder 7 计数")

    # ④ 1/3~1/2 仓丢前提
    rep("| 1/3~1/2 仓做短线 | 用 1/3~1/2 仓去挣快钱，剩下的仓位用追踪止损方式操作 |",
        "| 1/3~1/2 仓做短线 | **前提是已持仓、股票飙涨且严重超买、远离 30 周均线时**，用 1/3~1/2 仓去挣快钱，剩下的仓位用追踪止损方式操作。**这不是通用建仓比例** |",
        "1/3~1/2 仓前提")

    # ⑤ 期权：原文编号只有 5 条，第 6 条是我的立场归纳
    rep("**六条操作规则**：",
        "**五条编号规则 + 一条立场**（原文编号到 5；covered call 那条是正文立场，未编号）：",
        "五条而非六条")
    rep("| 6 | 不为了收期权费卖出 covered call：「不赞成为多挣几块钱，卖出以第二阶段的股票为标的的看涨期权，却丢掉了这只股票在第二阶段上涨的利润」 |",
        "| **立场** | 不为了收期权费卖出 covered call：「不赞成为多挣几块钱，卖出以第二阶段的股票为标的的看涨期权，却丢掉了这只股票在第二阶段上涨的利润」 |",
        "covered call 改立场")
    rep("> 2. 给六条期权规则，重点是「标的必须在对的阶段」。",
        "> 2. 给五条编号期权规则（+ covered call 立场），重点是「标的必须在对的阶段」。",
        "Agent instruction 六条→五条")

    # ⑥ 杠杆原话在第 7 章
    rep("**杠杆的真相**：\n> 「买入期权是一种**控制风险并提高杠杆率**的方法」\n> 算例：标的涨 60% 时，看涨期权涨 **1000%**（第 9 章得州仪器）",
        "**杠杆的真相**：\n> 「买入期权是一种**控制风险并提高杠杆率**的方法」——原话在**第 7 章**（卖空那章），第 9 章展开。\n> 算例：标的 +60% 时看涨期权 **+1000%**（第 9 章，得州仪器）",
        "杠杆章节归属")

    # ⑦ 期权到期时间补 45~50 天
    rep("| 3 | 离行权日留 **2~3 个月** |",
        "| 3 | 离行权日留 **2~3 个月**；另处补充「**绝不能少于 45~50 天**」 |",
        "45~50 天")

    # ⑧ 通用汽车补限制
    rep("| 6 | **通用汽车** | 「如果通用汽车拒绝下跌，大盘也很难一直下跌」——用龙头股当指标 |",
        "| 6 | **通用汽车** | 「如果通用汽车拒绝下跌，大盘也很难一直下跌」——用一只龙头股当代理指标。**局限**：作者用的是他那个年代的通用汽车，换成今天的龙头需要自己重新验证 |",
        "通用汽车局限")

    # ⑨ 期货一节补进来
    rep("### 用基金替代个股（第 9 章）",
        """### 期货（第 9 章，上一版完全没提）

| 要点 | 内容 |
|---|---|
| 态度 | 比期权**更谨慎**，只作介绍不作推荐 |
| 趋势判定 | 橙汁期货例子用 **40 天均线**（不是 30 周） |
| 保证金 | 「每份合约 **7 500 元**保证金」 |
| 风险 | 保证金交易**放大杠杆**，亏损可能超过本金 |
| 适合谁 | 明确限定为**极少数专业投机者** |

### 用基金替代个股（第 9 章）""",
        "期货一节")

    # ⑩ Overview 里「不能评估…该持几只股票」与新内容冲突
    rep("- **不能**评估：具体买什么、买多少、什么时候买。",
        "- **不能**评估：具体买哪只（不推荐个股）、精确价位。",
        "Overview 不能评估")
    rep("- **不能**评估：估值、财报细节、日内做 T、ETF/量化。",
        "- **不能**评估：估值（PE/PB/DCF）、财报细节、日内做 T、ETF/量化。",
        "Overview 不能评估(备用)")

    # ⑪ L289 附近「不讨论分散度」删掉
    rep("> 4. **分散度（该持几只）不讨论**",
        "> 4. **分散度有数字**（见 DIMENSION 3.6 末段）",
        "分散度旧话(1)")
    rep("4. **分散度（该持几只）不讨论**",
        "4. **分散度有数字**（见 DIMENSION 3.6 末段）",
        "分散度旧话(2)")
    rep("不讨论分散度（该持几只）",
        "分散度见下节末段（1~2.5 万 ≤6 只；数十万 10~20 只）",
        "分散度旧话(3)")

    # ⑫ 「本书未给公式」旧话
    rep("⚠️ 具体价位**本书未给公式**，只能说挂在关键支撑下方",
        "⚠️ 具体价位按 DIMENSION 3.5 的七条落位规则给（前期低点/整数关口/突破点下方 4%~6%/30 周均线/15% 上限），不是「没有公式」",
        "未给公式旧话")

    # ⑬ D6 里 Q6 的替代判据：跌破均线多久算失效
    rep("| 4 | **阶段判定有标准，但边界模糊**（跌破均线多久算失效没定义）。遇到边界情况要说「这本书没讲清」。 |",
        "| 4 | **阶段判定有标准，但「跌破均线多久算失效」确实没定义**。不过书里给了替代判据：只要①均线仍上升 ②股价回落不低于前一个调整低点，短暂跌破也可以继续持有。别只说「没讲清」 |",
        "Critical Reminder 4 替代判据")

    P.write_text(t, encoding="utf-8")
    print(f"\n成功 {n} 处，失败 {len(fails)} 处")
    if fails:
        for f in fails:
            print(f"  ! {f}")
        sys.exit(1)


if __name__ == "__main__":
    main()
