def run(path, reps, label):
    t = path.read_text(encoding="utf-8")
    n, fails = 0, []
    for old, new, tag in reps:
        if old in t:
            t = t.replace(old, new)
            n += 1
            print(f"  ✓ {tag}")
        else:
            fails.append(tag)
    path.write_text(t, encoding="utf-8")
    print(f"{label}: {n}/{len(reps)}")
    if fails:
        print("  失败: " + " | ".join(fails))
    return fails


