def main():
    todo = [f.stem for f in sorted(INC.glob("*.md"))
            if "第二轮增量" not in (MG / f.name).read_text(encoding="utf-8")]
    ok, miss = 0, []
    for bucket in todo:
        bpre = bucket.split("-")[0]
        mp = RES / f"_merge_map_{bucket}.json"
        if mp.exists():
            continue
        t = (INC / f"{bucket}.md").read_text(encoding="utf-8")
        entries = []
        for m in re.finditer(r"^## (B\d{2}-\d{3}) · (.+)$", t, re.M):
            cid, name = m.group(1), m.group(2)
            seg = t[m.start():m.start() + 600]
            pid = re.search(r"\*\*P(\d{4})\*\*", seg)
            key = f"P{pid.group(1)}" if pid else None
            oid = re.search(r"期次\s*\|\s*`([A-Za-z0-9]{12,24})`", seg)
            ts = re.search(r"`\[(\d{2}:\d{2}:\d{2})\]`", seg)
            oid = oid.group(1) if oid else ""
            ts = ts.group(1) if ts else ""
            # 取动作摘要做 brief
            act = re.search(r"\*\*动作\*\*[^\n]*：(.{0,60})", seg)
            brief = (act.group(1).strip() if act else name)[:40]
            dest = J.get(key, {}).get(bpre)
            if not dest:
                miss.append(f"{bucket} {cid} ({key})")
                continue
            if dest.startswith("single:"):
                entries.append({"cid": cid, "mode": "single", "oid": oid, "ts": ts,
                                "single_id": "S", "single_name": dest[7:],
                                "single_body": f"触发：{name} 动作：见桶文件 {cid} 候选"
                                               f"；本条判定为独立规则，桶内无同类节点。"
                                               f" 具体数字：见候选。 原话：> [{ts}] 见 "
                                               f"_规则候选/ 对应批次"})
            else:
                entries.append({"cid": cid, "mode": "merge", "target": dest,
                                "oid": oid, "ts": ts, "brief": brief})
        if entries:
            mp.write_text(json.dumps(entries, ensure_ascii=False, indent=1), encoding="utf-8")
            n_m = sum(1 for e in entries if e["mode"] == "merge")
            n_s = len(entries) - n_m
            print(f"  ✓ {bucket}: {len(entries)} 条（归入{n_m}/单列{n_s}）")
            ok += 1
    print(f"\n生成 {ok} 桶映射；未判定 {len(miss)} 条")
    for x in miss[:20]:
        print("  ", x)


if __name__ == "__main__":
    main()