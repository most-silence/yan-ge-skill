TS_LINE = re.compile(r"^\[(\d{2}:\d{2}:\d{2})\]\s?(.*)$")


def load_lines(eid):
    hits = list(TXT_DIR.glob(f"{eid}_*._clean.txt"))
    if len(hits) != 1:
        raise SystemExit(f"eid {eid} 清洗稿数量异常：{hits}")
    raw = hits[0].read_text(encoding="utf-8", errors="ignore").splitlines()
    out = []
    for ln in raw:
        m = TS_LINE.match(ln.strip())
        if m:
            out.append((m.group(1), ln.strip()))
    if not out:
        raise SystemExit(f"eid {eid} 没有解析到带时间戳的行")
    return out


def find(lines, ts, frag, start=0):
    for i in range(start, len(lines)):
        if lines[i][0] == ts and frag in lines[i][1]:
            return i
    raise SystemExit(f"找不到行：[{ts}] 含「{frag}」")


def build(name):
    eid, t1, f1, t2, f2 = SPECS[name]
    lines = load_lines(eid)
    i = find(lines, t1, f1)
    j = find(lines, t2, f2, start=i)
    block = [lines[k][1] for k in range(i, j + 1)]
    if any(not ln.startswith("[") for ln in block):
        raise SystemExit(f"{name} 截取到非引文行")
    body = "\n".join("> " + ln for ln in block)
    tail = f"—— `{eid}` `[{lines[i][0]}]`~`[{lines[j][0]}]`"
    return body + "\n\n" + tail


def main():
    if not TPL.exists():
        raise SystemExit(f"模板不存在：{TPL}")
    text = TPL.read_text(encoding="utf-8")
    used = []
    for m in re.finditer(r"<<(Q\d+)>>", text):
        used.append(m.group(1))
    missing = [q for q in used if q not in SPECS]
    if missing:
        raise SystemExit(f"模板里有未定义的占位符：{missing}")
    for q in used:
        text = text.replace(f"<<{q}>>", build(q))
    leftovers = re.findall(r"<<Q\d+>>", text)
    if leftovers:
        raise SystemExit(f"仍有未替换占位符：{leftovers}")
    OUT.write_text(text, encoding="utf-8")
    print(f"已生成 {OUT}（{len(used)} 个引文块）")
    print("未使用的 spec：", sorted(set(SPECS) - set(used)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
