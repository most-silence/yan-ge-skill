def block(eid, anchor, n):
    """从 anchor 所在行起取连续 n 行，返回渲染好的引用块"""
    rows = SRC[eid]
    idx = None
    for i, (ts, tx) in enumerate(rows):
        if anchor in tx:
            idx = i
            break
    if idx is None:
        raise SystemExit(f"anchor 未找到: {eid} / {anchor}")
    seg = rows[idx: idx + n]
    if len(seg) < n:
        raise SystemExit(f"行数不足: {eid} / {anchor}")
    lines = "\n".join(f"> [{ts}] {tx}" for ts, tx in seg)
    t1, t2 = seg[0][0], seg[-1][0]
    return f"**原话**：\n\n{lines}\n\n—— `{eid}` `[{t1}]`~`[{t2}]`\n"


