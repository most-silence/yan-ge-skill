def block(eid, ts, n):
    i = _idx(eid, ts)
    seg = LINES[eid][i:i + n]
    body = "\n".join(f"> [{t}] {x}" for t, x in seg)
    return f"{body}\n\n—— `{eid}` `[{seg[0][0]}]`~`[{seg[-1][0]}]`"


def Q(*blocks):
    return "\n\n".join(block(*b) for b in blocks)


