ROOT = Path(__file__).resolve().parent.parent
BATCH = ROOT / "sources" / "05-播客转写" / "_batches" / "batch-53.md"
OUT = ROOT / "sources" / "05-播客转写" / "_规则候选" / "batch-53.md"

EIDS = {
    1: "ZnssKc2mYyPu",
    2: "XpSrXLKoIOel",
    3: "GNTsKGypN4n9",
    4: "6acc5454195d838e2af0788d",
}

LINE_RE = re.compile(r"^\[(\d{2}:\d{2}:\d{2})\] (.*)$")
HDR_RE = re.compile(r"^## (\d)\. ")

eps, ep = {}, None
for ln in BATCH.read_text(encoding="utf-8").splitlines():
    m = HDR_RE.match(ln)
    if m:
        ep = int(m.group(1))
        eps[ep] = []
        continue
    if ep is None:
        continue
    m2 = LINE_RE.match(ln)
    if m2:
        eps[ep].append((m2.group(1), m2.group(2)))


def block(ep_no, t1, t2):
    eid = EIDS[ep_no]
    got = [(t, s) for (t, s) in eps[ep_no] if t1 <= t <= t2]
    if not got:
        raise SystemExit(f"抽取为空: ep{ep_no} {t1}~{t2}")
    if got[0][0] != t1 or got[-1][0] != t2:
        raise SystemExit(f"区间边界不符: ep{ep_no} {t1}~{t2} -> {got[0][0]}~{got[-1][0]}")
    lines = [f"> [{t}] {s}" for t, s in got]
    lines.append("")
    lines.append(f"—— `{eid}` `[{t1}]`~`[{t2}]`")
    return "\n".join(lines)


